/**
 * 全プロンプト共通のヘッダーブロック
 * @returns {string}
 */
export function getGlobalPreamble() {
  return [COMPANY_PROFILE, TARGET_CLIENTS, SOLUTION_AREAS, SOLUTION_SELLING_RULES].join("\n\n");
}

/**
 * プロンプト末尾に付与する共通フッター
 * @returns {string}
 */
export function getGlobalFooter() {
  return `【出力の最終チェック】
- 商品押し売りになっていないか確認する
- お客様の経営課題解決が主役になっているか確認する
- 営業担当者がそのまま使える実用レベルか確認する`;
}

/**
 * 共通ヘッダー + カテゴリ固有本文 + フッターを結合
 * @param {string} body
 * @returns {string}
 */
export function wrapPrompt(body) {
  return `${getGlobalPreamble()}\n\n${body}\n\n${getGlobalFooter()}`;
}

